exports.handler = async function (event) {
    // อนุญาตเฉพาะ POST เท่านั้น
    if (event.httpMethod !== 'POST') {
        return { statusCode: 405, body: JSON.stringify({ error: 'Method Not Allowed' }) };
    }

    // อ่านคำถามจาก body ที่ส่งมาจากหน้าเว็บ
    let text = '';
    try {
        const body = JSON.parse(event.body || '{}');
        text = (body.text || '').trim();
    } catch (e) {
        return { statusCode: 400, body: JSON.stringify({ error: 'รูปแบบคำขอไม่ถูกต้อง' }) };
    }

    if (!text) {
        return { statusCode: 400, body: JSON.stringify({ error: 'กรุณาระบุคำถาม' }) };
    }

    // อ่าน API Key จาก Environment Variable ของ Netlify (ตั้งค่าในหน้า Site configuration)
    // ไม่ฝังคีย์ไว้ในโค้ดไฟล์นี้ เพื่อความปลอดภัย
    const API_KEY = process.env.GEMINI_API_KEY;
    if (!API_KEY) {
        return {
            statusCode: 500,
            body: JSON.stringify({ error: 'ยังไม่ได้ตั้งค่า GEMINI_API_KEY ใน Netlify Environment Variables ครับ' })
        };
    }

    const promptContext = `คุณคือ AI มัคคุเทศก์ประจำวัดพระมหาธาตุวรมหาวิหาร จังหวัดนครศรีธรรมราช
หน้าที่ของคุณคือให้ข้อมูลเกี่ยวกับวัดแห่งนี้เท่านั้น (ประวัติ สถาปัตยกรรม สถานที่สำคัญ การเดินทาง มารยาทการเข้าชม ฯลฯ)

กติกาการตอบ:
1. ใช้ข้อมูลอ้างอิงด้านล่างนี้เป็นหลักในการตอบ ห้ามเดาหรือแต่งข้อมูลเอง หากไม่มีข้อมูลส่วนนั้นให้บอกตามตรงสั้นๆ ว่ายังไม่มีข้อมูล
2. ตอบให้สั้นและกระชับที่สุด ดึงเฉพาะเนื้อหาที่เกี่ยวข้องกับคำถามมาสรุปย่อเป็นภาษาพูดง่ายๆ ไม่ต้องเล่าทุกรายละเอียดที่มีในฐานข้อมูล ไม่ต้องมีคำนำหรือคำลงท้าย ความยาวปกติควรอยู่แค่ 1-3 ประโยค ยกเว้นผู้ถามขอให้อธิบายละเอียดจริงๆ
3. ห้ามแนะนำเว็บไซต์หรือแหล่งข้อมูลเพิ่มเติมท้ายคำตอบเป็นประจำ ให้พูดถึง ${OFFICIAL_URL}, เพจ Facebook ทางการ ${OFFICIAL_FACEBOOK_URL} หรือ ${OFFICIAL_NEWS_URL} เฉพาะกรณีที่ผู้ถามถามเรื่องข่าวสาร กิจกรรม เวลาเปิด-ปิด หรือข้อมูลที่ไม่มีอยู่ในฐานความรู้นี้เท่านั้น (เพจ Facebook มักอัปเดตข่าวสารบ่อยกว่าเว็บไซต์ แนะนำให้ใช้เพจนี้เป็นหลักสำหรับคำถามเรื่องข่าว/กิจกรรมล่าสุด)
4. ตอบด้วยภาษาเดียวกับคำถามของผู้ใช้เสมอ (ถามไทยตอบไทย ถามอังกฤษตอบอังกฤษ)
5. ตอบด้วยความสุภาพ เป็นกันเอง เหมือนคุยกับนักท่องเที่ยวตัวต่อตัว
6. หากคำถามไม่เกี่ยวข้องกับวัดพระมหาธาตุวรมหาวิหารเลย ให้ตอบสุภาพสั้นๆ ว่าคุณช่วยได้เฉพาะเรื่องเกี่ยวกับวัดแห่งนี้ แล้วชวนกลับมาถามเรื่องวัด

ข้อมูลอ้างอิง:
${TEMPLE_KNOWLEDGE}

คำถามจากนักท่องเที่ยว: ${text}

(สำคัญมาก: ตอบเป็นภาษาเดียวกับคำถามข้างต้นเท่านั้น หากคำถามเป็นภาษาไทยให้ตอบเป็นภาษาไทยทั้งหมด ห้ามตอบเป็นภาษาอังกฤษเด็ดขาด หากคำถามเป็นภาษาอังกฤษจึงค่อยตอบเป็นภาษาอังกฤษ ตอบสั้นกระชับ 1-3 ประโยค ไม่ต้องแนะนำเว็บไซต์เพิ่มเติมถ้าไม่ได้ถูกถามถึง)`;

    try {
        const response = await fetch('https://generativelanguage.googleapis.com/v1beta/interactions', {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
                'x-goog-api-key': API_KEY,
                'Api-Revision': '2026-05-20'
            },
            body: JSON.stringify({
                model: 'gemini-3.5-flash',
                input: promptContext
            })
        });

        if (!response.ok) {
            const errText = await response.text();
            console.error('Gemini API error:', response.status, errText);
            return {
                statusCode: 502,
                body: JSON.stringify({ error: 'เรียก Gemini API ไม่สำเร็จ (สถานะ ' + response.status + ')' })
            };
        }

        const data = await response.json();

        // Interactions API ตอบกลับเป็น steps array
        const reply = (data.steps || [])
            .filter(function (s) { return s.type === 'model_output'; })
            .flatMap(function (s) { return s.content || []; })
            .filter(function (c) { return c.type === 'text'; })
            .map(function (c) { return c.text; })
            .join('');

        return {
            statusCode: 200,
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ reply: reply || 'ขออภัยครับ ไม่พบคำตอบ กรุณาลองถามใหม่อีกครั้ง' })
        };
    } catch (err) {
        console.error('Function error:', err);
        return { statusCode: 500, body: JSON.stringify({ error: 'เกิดข้อผิดพลาดในระบบ กรุณาลองใหม่อีกครั้ง' }) };
    }
};
